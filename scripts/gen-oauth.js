#!/usr/bin/env node

/**
 * Generates `wol-highlights/lib/oauth.generated.js` from the OAuth credentials
 * in `.env` (or the environment).
 *
 * Why: Google's "Desktop app" OAuth clients require a client_secret on the
 * token exchange even when PKCE is used, so an end user cannot sign in with a
 * client_id alone. Bundling the shipped client credentials at build time keeps
 * them out of git while still giving users a working "Sign in with Google
 * Drive" button — the only per-user secret is their own refresh token.
 *
 * Sources, in priority order:
 *   1. `--from-json <client_secret_*.json>` (downloaded from Google Cloud Console)
 *   2. `WOL_GOOGLE_CLIENT_ID` / `WOL_GOOGLE_CLIENT_SECRET`
 *   3. `CHROME_CLIENT_ID` / `CHROME_CLIENT_SECRET`
 *
 * Missing credentials are not an error: the generated module simply
 * contains empty strings and Google Drive sync stays disabled at runtime.
 *
 * Usage:
 *   node scripts/gen-oauth.js [--from-json <path>] [--out <path>] [--check] [--quiet]
 */

const fs = require("fs");
const path = require("path");

const rootDir = path.resolve(__dirname, "..");
const defaultOutPath = path.join(rootDir, "wol-highlights", "lib", "oauth.generated.js");
const envPath = path.join(rootDir, ".env");

const ID_KEYS = ["WOL_GOOGLE_CLIENT_ID", "CHROME_CLIENT_ID"];
const SECRET_KEYS = ["WOL_GOOGLE_CLIENT_SECRET", "CHROME_CLIENT_SECRET"];

function firstNonEmpty(env, keys) {
  for (const key of keys) {
    const value = String(env?.[key] ?? "").trim();
    if (value) return { value, key };
  }
  return { value: "", key: null };
}

/**
 * Pure credential resolution. Never logs or returns anything but the values.
 * @param {Record<string, string|undefined>} env
 * @param {{clientId?: string, clientSecret?: string}|null} jsonCreds
 */
function resolveCredentials(env, jsonCreds) {
  const fromJsonId = String(jsonCreds?.clientId ?? "").trim();
  const fromJsonSecret = String(jsonCreds?.clientSecret ?? "").trim();
  const id = fromJsonId ? { value: fromJsonId, key: "--from-json" } : firstNonEmpty(env, ID_KEYS);
  const secret = fromJsonSecret
    ? { value: fromJsonSecret, key: "--from-json" }
    : firstNonEmpty(env, SECRET_KEYS);
  return { clientId: id.value, clientSecret: secret.value, source: id.key || secret.key || null };
}

/** Reads a Google Cloud Console `client_secret_*.json` file. */
function readClientSecretJson(filePath) {
  const parsed = JSON.parse(fs.readFileSync(filePath, "utf8"));
  const block = parsed.installed || parsed.web || parsed;
  return {
    clientId: String(block.client_id ?? "").trim(),
    clientSecret: String(block.client_secret ?? "").trim(),
  };
}

/** Renders the browser-side module consumed by `lib/sync.js`. */
function renderModule({ clientId, clientSecret }) {
  return `// @generated by scripts/gen-oauth.js — DO NOT EDIT, DO NOT COMMIT.
// Bundled Google OAuth client for Drive sync. The client secret of an installed
// app is not a confidential secret (it ships in the package either way); each
// user's refresh token is what must stay private. See README.
(function (scope) {
  "use strict";
  scope.WOL_GOOGLE_OAUTH = Object.freeze({
    clientId: ${JSON.stringify(clientId ?? "")},
    clientSecret: ${JSON.stringify(clientSecret ?? "")},
  });
})(typeof globalThis !== "undefined" ? globalThis : self);
`;
}

/** Minimal dotenv parsing: KEY=value, optional surrounding quotes, # comments. */
function parseEnvFile(contents) {
  const env = {};
  for (const rawLine of String(contents).split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const match = line.match(/^(?:export\s+)?([\w.-]+)\s*=\s*(.*)$/);
    if (!match) continue;
    let value = match[2].trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    env[match[1]] = value;
  }
  return env;
}

function loadDotEnv(filePath = process.env.WOL_ENV_FILE || envPath) {
  if (!filePath || !fs.existsSync(filePath)) return {};
  return parseEnvFile(fs.readFileSync(filePath, "utf8"));
}

function parseArgs(argv) {
  const options = { fromJson: null, out: defaultOutPath, check: false, quiet: false };
  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--from-json") options.fromJson = argv[++i] ?? null;
    else if (arg === "--out") options.out = argv[++i] ?? defaultOutPath;
    else if (arg === "--check") options.check = true;
    else if (arg === "--quiet") options.quiet = true;
    else if (arg === "--help" || arg === "-h") options.help = true;
    else throw new Error(`Unknown argument: ${arg}`);
  }
  return options;
}

function mask(value) {
  const text = String(value || "");
  if (!text) return "(empty)";
  return text.length <= 12 ? `${text.slice(0, 4)}…` : `${text.slice(0, 12)}…${text.slice(-4)}`;
}

function main(argv = process.argv.slice(2), ambientEnv = process.env) {
  const options = parseArgs(argv);
  if (options.help) {
    console.log("Usage: node scripts/gen-oauth.js [--from-json <path>] [--out <path>] [--check] [--quiet]");
    return 0;
  }
  const env = { ...loadDotEnv(), ...pickKnownKeys(ambientEnv) };
  const jsonCreds = options.fromJson ? readClientSecretJson(options.fromJson) : null;
  const creds = resolveCredentials(env, jsonCreds);

  fs.mkdirSync(path.dirname(options.out), { recursive: true });
  fs.writeFileSync(options.out, renderModule(creds), { encoding: "utf8", mode: 0o600 });

  const ready = Boolean(creds.clientId && creds.clientSecret);
  if (!options.quiet) {
    const relative = path.relative(rootDir, options.out);
    if (ready) {
      console.log(`[gen-oauth] wrote ${relative} (client_id ${mask(creds.clientId)}, secret ${mask(creds.clientSecret)}, source ${creds.source})`);
    } else {
      console.warn(
        `[gen-oauth] wrote ${relative} WITHOUT credentials — Google Drive sync stays disabled.\n` +
          `[gen-oauth] Provide them with one of:\n` +
          `  node scripts/gen-oauth.js --from-json ~/Downloads/client_secret_*.json\n` +
          `  WOL_GOOGLE_CLIENT_ID=... WOL_GOOGLE_CLIENT_SECRET=... (or CHROME_CLIENT_ID/CHROME_CLIENT_SECRET in .env)`
      );
    }
  }
  if (options.check && !ready) return 1;
  return 0;
}

/** Keeps only the keys this script understands, so unrelated env can't leak in. */
function pickKnownKeys(source = process.env) {
  const env = {};
  for (const key of [...ID_KEYS, ...SECRET_KEYS]) {
    if (source?.[key] !== undefined) env[key] = source[key];
  }
  return env;
}

if (require.main === module) {
  try {
    process.exitCode = main();
  } catch (err) {
    console.error(`[gen-oauth] ${err?.message || err}`);
    process.exitCode = 1;
  }
}

module.exports = {
  resolveCredentials,
  renderModule,
  parseEnvFile,
  readClientSecretJson,
  loadDotEnv,
  parseArgs,
  main,
  defaultOutPath,
};
