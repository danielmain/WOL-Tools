//! Rust port of `wol-highlights/lib/tokenize.js`.
//!
//! JW Library counts a token as a word (a run of letters/numbers/connector
//! punctuation) or a single non-space character. Whitespace is not a token.
//!
//! The JS implementation iterates **UTF-16 code units**, so characters outside
//! the BMP (emoji, rare CJK) become **two** single-unit tokens rather than one
//! wide token: neither half of a surrogate pair matches `\p{L}`/`\p{N}`. This
//! port reproduces that exactly — token indices must match `wolMarks` ranges
//! byte-for-byte in behaviour, not just in spirit.
//!
//! Verified against real backups: document `2025441` paragraph 7, and `nwtsty`
//! Exodus 5:9 and 6:6. Cross-checked against the JS implementation by
//! `tests/tokenize_parity.rs` (fixtures generated by
//! `wol-highlights/test/tokenize-parity.mjs`).

use std::ops::Range;

use unicode_general_category::{get_general_category, GeneralCategory};

/// A token as a half-open range of UTF-16 code-unit offsets into the source.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct Token {
    pub start: usize,
    pub end: usize,
}

impl Token {
    pub const fn new(start: usize, end: usize) -> Self {
        Self { start, end }
    }

    pub fn range(self) -> Range<usize> {
        self.start..self.end
    }

    pub fn is_empty(self) -> bool {
        self.end <= self.start
    }
}

/// Matches JS `\p{L}` (General_Category Lu, Ll, Lt, Lm, Lo).
///
/// `char::is_alphabetic()` is *not* equivalent: it implements the Unicode
/// `Alphabetic` property, which also covers combining marks such as Hebrew
/// niqqud (`\u{05B8}`). The extension treats those as standalone tokens, so the
/// general category is what matters here.
fn is_letter(character: char) -> bool {
    matches!(
        get_general_category(character),
        GeneralCategory::UppercaseLetter
            | GeneralCategory::LowercaseLetter
            | GeneralCategory::TitlecaseLetter
            | GeneralCategory::ModifierLetter
            | GeneralCategory::OtherLetter
    )
}

/// Matches JS `\p{N}` (General_Category Nd, Nl, No).
fn is_number(character: char) -> bool {
    matches!(
        get_general_category(character),
        GeneralCategory::DecimalNumber
            | GeneralCategory::LetterNumber
            | GeneralCategory::OtherNumber
    )
}

/// Matches JS `\p{Pc}` — connector punctuation.
fn is_connector(character: char) -> bool {
    matches!(
        character,
        '\u{005F}'
            | '\u{203F}'
            | '\u{2040}'
            | '\u{2054}'
            | '\u{FE33}'
            | '\u{FE34}'
            | '\u{FE4D}'..='\u{FE4F}'
            | '\u{FF3F}'
    )
}

/// Matches the JS `WORD = /[\p{L}\p{N}\p{Pc}]/u` character class.
fn is_word(character: char) -> bool {
    is_letter(character) || is_number(character) || is_connector(character)
}

/// Matches the JS `SPACE` character class (`\s` plus explicit non-ASCII spaces).
///
/// `char::is_whitespace()` follows the Unicode `White_Space` property, which is
/// one character wider than JS: U+0085 NEXT LINE is whitespace in Unicode but
/// *not* in `\s`, so the extension emits it as a token.
fn is_space(character: char) -> bool {
    (character.is_whitespace() && character != '\u{0085}')
        || matches!(
            character,
            '\u{00A0}'
                | '\u{1680}'
                | '\u{2000}'..='\u{200A}'
                | '\u{2028}'
                | '\u{2029}'
                | '\u{202F}'
                | '\u{205F}'
                | '\u{3000}'
                | '\u{FEFF}'
        )
}

/// Number of UTF-16 code units needed for `character`.
const fn utf16_len(character: char) -> usize {
    character.len_utf16()
}

/// Split `text` into tokens, mirroring `tokenize()` in `tokenize.js`.
pub fn tokenize(text: &str) -> Vec<Token> {
    let mut tokens = Vec::new();
    let mut index = 0usize;
    let mut chars = text.chars().peekable();
    let mut pending: Option<char> = chars.next();

    while let Some(character) = pending {
        if is_space(character) {
            index += utf16_len(character);
            pending = chars.next();
            continue;
        }

        // Astral characters are two lone UTF-16 code units, and neither half
        // matches the JS `WORD` class, so each half is its own token. This must
        // come before the word check: an astral letter such as 𠀀 would otherwise
        // start a what-looks-like word run.
        let width = utf16_len(character);
        if width == 2 {
            tokens.push(Token::new(index, index + 1));
            tokens.push(Token::new(index + 1, index + 2));
            index += 2;
            pending = chars.next();
            continue;
        }

        if is_word(character) {
            let start = index;
            index += 1;
            pending = chars.next();
            while let Some(next) = pending {
                // Astral characters never match the JS `WORD` class (a lone
                // surrogate is not a letter), so they end the run.
                if !is_word(next) || utf16_len(next) != 1 {
                    break;
                }
                index += 1;
                pending = chars.next();
            }
            tokens.push(Token::new(start, index));
            continue;
        }

        tokens.push(Token::new(index, index + 1));
        index += 1;
        pending = chars.next();
    }

    tokens
}

/// Total UTF-16 length of `text` (the coordinate space tokens live in).
pub fn utf16_len_of(text: &str) -> usize {
    text.chars().map(utf16_len).sum()
}

/// Map a token index range (inclusive end, as stored by `wolMarks`) to the
/// covered UTF-16 character range, or `None` when the range is invalid.
pub fn token_range_to_chars(tokens: &[Token], start_token: i64, end_token: i64) -> Option<Range<usize>> {
    if start_token < 0 || end_token < start_token {
        return None;
    }
    let start = tokens.get(usize::try_from(start_token).ok()?)?;
    let end = tokens.get(usize::try_from(end_token).ok()?)?;
    Some(start.start..end.end)
}

/// Token index range covering a UTF-16 character window, mirroring the overlap
/// test `tokenRangeForBlock()` uses in `highlight.js`.
pub fn char_window_to_token_range(
    tokens: &[Token],
    char_start: usize,
    char_end: usize,
) -> Option<(usize, usize)> {
    if char_start >= char_end {
        return None;
    }
    let mut first: Option<usize> = None;
    let mut last: usize = 0;
    for (index, token) in tokens.iter().enumerate() {
        if token.start.max(char_start) < token.end.min(char_end) {
            first.get_or_insert(index);
            last = index;
        }
    }
    first.map(|start| (start, last))
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Slice the UTF-8 string using UTF-16 token coordinates.
    fn texts(input: &str) -> Vec<String> {
        let units: Vec<u16> = input.encode_utf16().collect();
        tokenize(input)
            .into_iter()
            .map(|token| String::from_utf16_lossy(&units[token.start..token.end]))
            .collect()
    }

    /// Reference case documented in `tokenize.js`: document 2025441 ¶7.
    #[test]
    fn splits_words_and_punctuation_like_the_extension() {
        assert_eq!(
            texts("«Почему?» — спросил он."),
            vec!["«", "Почему", "?", "»", "—", "спросил", "он", "."]
        );
    }

    #[test]
    fn keeps_connector_punctuation_inside_words() {
        assert_eq!(texts("snake_case"), vec!["snake_case"]);
        assert_eq!(texts("a_b c"), vec!["a_b", "c"]);
    }

    #[test]
    fn skips_all_whitespace_flavours() {
        let input = "a\u{00A0}b\u{2003}c\u{3000}d\u{FEFF}e";
        assert_eq!(texts(input), vec!["a", "b", "c", "d", "e"]);
    }

    #[test]
    fn soft_hyphen_and_zero_width_are_individual_tokens() {
        assert_eq!(texts("co\u{00AD}op"), vec!["co", "\u{00AD}", "op"]);
        let zero_width = "a\u{200B}b";
        assert_eq!(texts(zero_width).len(), 3);
    }

    #[test]
    fn astral_characters_become_two_code_unit_tokens() {
        // The JS engine walks UTF-16 code units, so an astral character is two
        // lone surrogates — neither matches `WORD`, so it yields two tokens.
        let tokens = tokenize("a🙂b");
        assert_eq!(tokens.len(), 4);
        assert_eq!(tokens[0], Token::new(0, 1));
        assert_eq!(tokens[1], Token::new(1, 2));
        assert_eq!(tokens[2], Token::new(2, 3));
        assert_eq!(tokens[3], Token::new(3, 4));
        assert_eq!(utf16_len_of("a🙂b"), 4);

        // Astral letters behave the same way (they never join a word run).
        let astral_letter = tokenize("a𠀀b");
        assert_eq!(astral_letter.len(), 4);
        assert_eq!(astral_letter[1], Token::new(1, 2));
        assert_eq!(astral_letter[2], Token::new(2, 3));
    }

    #[test]
    fn verse_reference_tokens_match_reference_split() {
        // "5:9" style tokenization used by nwtsty Exodus verses.
        assert_eq!(texts("5:9"), vec!["5", ":", "9"]);
        assert_eq!(texts("6:6"), vec!["6", ":", "6"]);
    }

    #[test]
    fn empty_and_whitespace_only_inputs_have_no_tokens() {
        assert!(tokenize("").is_empty());
        assert!(tokenize("  \n\t\u{00A0}").is_empty());
    }

    #[test]
    fn char_windows_map_back_to_token_ranges() {
        let tokens = tokenize("one two three");
        assert_eq!(char_window_to_token_range(&tokens, 4, 7), Some((1, 1)));
        assert_eq!(char_window_to_token_range(&tokens, 0, 3), Some((0, 0)));
        assert_eq!(char_window_to_token_range(&tokens, 0, 13), Some((0, 2)));
        assert_eq!(char_window_to_token_range(&tokens, 3, 3), None);
        assert_eq!(char_window_to_token_range(&tokens, 3, 4), None);
    }

    #[test]
    fn token_ranges_round_trip_to_char_offsets() {
        let tokens = tokenize("one two three");
        assert_eq!(token_range_to_chars(&tokens, 2, 2), Some(8..13));
        assert_eq!(token_range_to_chars(&tokens, 0, 0), Some(0..3));
        assert_eq!(token_range_to_chars(&tokens, 2, 1), None);
        assert_eq!(token_range_to_chars(&tokens, -1, 0), None);
        assert_eq!(token_range_to_chars(&tokens, 0, 9), None);
    }
}
